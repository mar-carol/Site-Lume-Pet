      </section>

      <section id="armazenamento">
        <h2>6. Armazenamento e segurança</h2>
        <p>Adotamos medidas técnicas e organizacionais para proteger seus dados, como senhas criptografadas e acesso restrito às informações. Mantemos os dados pelo tempo necessário para cumprir as finalidades acima e as obrigações legais; depois disso, eles são excluídos ou anonimizados.</p>
        <p>Nenhum sistema é 100% seguro. Se houver um incidente que possa afetar você, avisaremos você e a Autoridade Nacional de Proteção de Dados (ANPD), conforme a lei.</p>
      </section>

