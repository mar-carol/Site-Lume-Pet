          <li><strong>ONGs parceiras</strong>, que recebem os valores das vendas e doações. Em regra, os valores são repassados sem identificar o comprador, salvo se você optar por se identificar.</li>
          <li><strong>Autoridades</strong>, quando houver obrigação legal ou ordem judicial.</li>
        </ul>
      </section>

